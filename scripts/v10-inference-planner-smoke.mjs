import assert from 'node:assert/strict';
import {planV10FollowUps} from '../public/v10-inference-planner.mjs';
const config={tpms:'gyroid',frequency:1,threshold:0,roughness:0};
const make=(s,flow,name='test')=>({name,config,solidFraction:s,relativeOpen:flow,converged:true,meetsTarget:s>=.25&&s<=.75&&flow>=.20});
let plan=planV10FollowUps([make(.12,.8)]);
assert.ok(plan.length>0);
assert.ok(plan.some(t=>t.config.threshold<config.threshold),'too little solid should test more material');
assert.match(plan[0].reason,/Too little solid/);
plan=planV10FollowUps([make(.83,.05)]);
assert.ok(plan.some(t=>t.config.threshold>0),'excessive solid should test more open pores');
plan=planV10FollowUps([make(.5,.12)]);
assert.ok(plan[0].config.threshold>0,'low throughput should trigger connectivity hypothesis');
plan=planV10FollowUps([make(.5,.3)]);
assert.ok(plan.some(t=>t.config.frequency!==1),'feasible geometry should test spacing');
assert.ok(plan.every(x=>x.reason.length>16&&Number.isFinite(x.observation.relativeOpen)));
assert.deepEqual(planV10FollowUps([make(.5,.3)],new Set(plan.map(x=>JSON.stringify(x.config)))),[],'do not repeat tested models');
assert.deepEqual(planV10FollowUps([]),[]);
assert.deepEqual(planV10FollowUps([make(.5,.3)],new Set(),0),[],'limit zero means no work');
assert.throws(()=>planV10FollowUps([],new Set(),999),/invalid/);
console.log('Evidence-directed bounded experiment planner PASS');
