import assert from 'node:assert/strict';
import {compareToReference,selectScreeningResult,shouldPromote} from '../public/discovery-gates.mjs';
const ref={id:0,label:'Open cavity',config:null,accepted:true,score:3.133};
const weak={id:1,label:'Membrane',config:{tpms:'neovius'},accepted:true,score:2.95};
const strong={id:2,label:'Better membrane',config:{tpms:'gyroid'},accepted:true,score:3.31};
let r=selectScreeningResult([ref,weak]);
assert.equal(r.status,'no-improvement');
assert.equal(r.incumbent.config,null,'losing membrane cannot be promoted as winner');
assert.equal(r.seed.config.tpms,'neovius','the best rejected design can seed the next local mutation');
assert.equal(compareToReference(ref,weak).ok,false);
r=selectScreeningResult([ref,weak,strong]);
assert.equal(r.status,'candidate-provisional');
assert.equal(r.incumbent.id,2);
assert.equal(shouldPromote(ref,r.incumbent,weak).ok,false);
assert.equal(shouldPromote(ref,selectScreeningResult([ref,weak]).incumbent,strong).ok,true);
assert.equal(selectScreeningResult([ref,{...strong,accepted:false}]).status,'no-improvement');
assert.equal(selectScreeningResult([ref,{...strong,score:NaN}]).status,'no-improvement');
assert.equal(selectScreeningResult([{...ref,accepted:false},strong]).status,'invalid-reference');
assert.equal(selectScreeningResult([{...ref,score:0},strong]).status,'invalid-reference');
assert.equal(compareToReference(ref,{...strong,score:3.15}).ok,false,'suppress noisy marginal gains');
assert.throws(()=>selectScreeningResult([]),/empty campaign/);
console.log('Evidence gate PASS: losing geometry not promoted; invalid evidence rejected; exploration seed retained.');
