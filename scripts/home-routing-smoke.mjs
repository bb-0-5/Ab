import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import worker from '../public/_worker.js';
const requests=[];
const env={ASSETS:{async fetch(req) {
  const target=new URL(req.url);
  requests.push(target.pathname);
  return new Response('asset:'+target.pathname,{status:200,headers:{'Content-Type':'text/html'}});
}}};
const run=(path)=>worker.fetch(new Request('https://abovebound.org'+path),env);
const home=await run('/');
assert.equal(home.status,302,'homepage redirects to the latest lab');
assert.match(home.headers.get('Location'),/\/membrane\.html\?release=v10-membrane-home-20261015-r2/);
assert.match(home.headers.get('Cache-Control'),/no-store/);
assert.equal((await run('/index.html')).status,302,'index.html also redirects');
const legacy=await run('/simulator.html');
assert.equal(legacy.status,200,'original simulator remains accessible');
assert.equal(await legacy.text(),'asset:/','original content served from built /');
assert.match(legacy.headers.get('Cache-Control'),/no-store/);
const membrane=await run('/membrane.html');
assert.equal(membrane.status,200);
assert.equal(await membrane.text(),'asset:/membrane.html');
assert.match(membrane.headers.get('Cache-Control'),/no-store/);
const script=await run('/membrane-ui.mjs');
assert.match(script.headers.get('Cache-Control'),/no-store/);
const originalAsset=await run('/assets/app-c3d7.js');
